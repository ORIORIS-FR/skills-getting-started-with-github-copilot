def test_delete_returns_404_for_unregistered_participant(client):
    # Arrange
    activity_name = "Chess Club"
    participants_before = activities[activity_name]["participants"].copy()
    email = "not.registered@mergington.edu"
    assert email not in participants_before

    # Act
    response = client.delete(
        f"/activities/{activity_name}/participants",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 404
    assert response.json() == {
        "detail": "Student is not signed up for this activity"
    }
    assert activities[activity_name]["participants"] == participants_before